#!/usr/bin/env node
// Turns the generated dataset (dataset.json) into one idempotent SQL transaction that
// replaces the Underground dev content. Deterministic: no Math.random — the "random-looking"
// spread comes from a hash of stable indices, so re-running produces byte-identical SQL.
//
// Usage: node build-seed.mjs dataset.json > seed.sql

import { readFileSync } from 'node:fs'

const ds = JSON.parse(readFileSync(process.argv[2], 'utf8'))
// MVP without payments (brief 2026-11-11): every demo event is free unless UG_SEED_PAID=1 asks for the
// original prices (the payment branch). Free events get no orders and no escrow rows.
if (process.env.UG_SEED_PAID !== '1') for (const e of ds.events) e.cost_type = 'free'

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`)
const arr = (xs) => `ARRAY[${xs.map(q).join(',')}]::text[]`
const rnd = (seed) => {
  let h = 2166136261
  for (const ch of String(seed)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619) }
  return ((h >>> 0) % 100000) / 100000
}
const uref = (email) => `(SELECT id FROM users WHERE lower(email)=lower(${q(email)}))`

const people = ds.people ?? []
const events = ds.events ?? []
const reviews = ds.reviews ?? []
const posts = ds.posts ?? []
const comments = ds.comments ?? []

const organizers = people.map((p, i) => ({ ...p, i })).filter((p) => p.is_organizer)
const attendees = people.map((p, i) => ({ ...p, i })).filter((p) => !p.is_organizer)
if (!organizers.length || !attendees.length) throw new Error('dataset needs both organizers and attendees')

const orgByName = new Map()
organizers.forEach((o) => orgByName.set(o.name.toLowerCase(), o))
const eventOrg = events.map((e, i) => {
  const hit = orgByName.get(String(e.organizer_name || '').toLowerCase())
  return hit ? hit.i : organizers[i % organizers.length].i
})

const out = []
const w = (s) => out.push(s)

w('-- Underground dev content seed — generated by build-seed.mjs. Do not hand-edit.')
w('BEGIN;')
w('')

// ---------------------------------------------------------------- gazetteer
// The shipped gazetteer (migration 0015) has 12 Ukrainian cities; the other 10 below were
// missing, and a missing city is silent — cities::resolve returns all-NULL, so the event is
// stored with no country and no coordinates and drops out of the distance boost, the "поряд"
// reason and the same-country boost in /api/discover.
//
// country MUST be 'Україна', the spelling already in the gazetteer and the only one
// currency.rs maps to UAH. 'Ukraine' geocodes fine and then prices events in the wrong
// currency — a defect with no error message anywhere.
w('-- Ukrainian cities: 12 ship in migration 0015, these fill in the rest.')
const UA_CITIES = [
  ['Київ', 50.4501, 30.5234], ['Львів', 49.8397, 24.0297], ['Одеса', 46.4825, 30.7233],
  ['Харків', 49.9935, 36.2304], ['Дніпро', 48.4647, 35.0462], ['Івано-Франківськ', 48.9226, 24.7111],
  ['Ужгород', 48.6208, 22.2879], ['Чернівці', 48.2921, 25.9358], ['Вінниця', 49.2331, 28.4682],
  ['Тернопіль', 49.5535, 25.5948], ['Полтава', 49.5883, 34.5514], ['Запоріжжя', 47.8388, 35.1396],
  ['Черкаси', 49.4444, 32.0598], ['Житомир', 50.2547, 28.6587], ['Рівне', 50.6199, 26.2516],
  ['Луцьк', 50.7472, 25.3254], ['Хмельницький', 49.4229, 26.9871], ['Кропивницький', 48.5079, 32.2623],
  ['Суми', 50.9077, 34.7981], ['Чернігів', 51.4982, 31.2893], ['Кривий Ріг', 47.9105, 33.3918],
  ['Миколаїв', 46.9750, 31.9946],
]
w('INSERT INTO cities (name, country, lat, lng) VALUES')
w(UA_CITIES.map(([n, la, lo]) => `  (${q(n)}, 'Україна', ${la}, ${lo})`).join(',\n'))
w('ON CONFLICT (lower(name)) DO NOTHING;')
w('')

// ---------------------------------------------------------------- purge
w('-- Purge the security-audit probe accounts and the old thin seed. Dev data only, dumped first.')
w("DELETE FROM users WHERE email LIKE 'probe-%' OR email LIKE 'lockout-probe%'")
w("   OR email LIKE 'authzprobe%' OR email LIKE 'deleted+%' OR email LIKE '%@example.invalid';")
w('DELETE FROM events;  -- cascades: tickets, orders, reviews, saves, event posts, staff')
w('DELETE FROM posts;   -- standalone posts left by the old seed')
w("DELETE FROM users WHERE email LIKE '%@underground.dev'")
w("   AND lower(email) NOT IN ('user@underground.dev','maker@underground.dev','admin@underground.dev');")
w('')

// ---------------------------------------------------------------- people
// Every seeded account reuses the existing test account's argon2 hash, so they all share
// that one known password and no secret is written into this file.
w('-- People. Password for every seeded account = the standing test password.')
w("CREATE TEMP TABLE _pw AS SELECT password_hash AS h FROM users WHERE lower(email)='user@underground.dev';")
w('INSERT INTO users (email, name, bio, avatar_url, cover_url, is_organizer, verified, role, password_hash, dob, created_at) VALUES')
w(people.map((p, i) => {
  const avatar = `https://picsum.photos/seed/${p.avatar_seed}/240/240`
  const cover = p.is_organizer ? q(`https://picsum.photos/seed/${p.avatar_seed}cv/1200/400`) : 'NULL'
  // A date of birth is what the 18+ gate reads at checkout; without one every age-restricted
  // event is unbuyable, which would read as a bug rather than as missing seed data.
  const age = 19 + Math.floor(rnd('dob' + i) * 26)
  return `  (${q(p.email)}, ${q(p.name)}, ${q(p.bio)}, ${q(avatar)}, ${cover}, ${p.is_organizer}, ` +
    `${p.verified}, 'USER', (SELECT h FROM _pw), (now() - interval '${age} years')::date, ` +
    `now() - interval '${30 + i * 3} days')`
}).join(',\n'))
w('ON CONFLICT (lower(email)) DO UPDATE SET name=EXCLUDED.name, bio=EXCLUDED.bio,')
w('  avatar_url=EXCLUDED.avatar_url, cover_url=EXCLUDED.cover_url,')
w('  is_organizer=EXCLUDED.is_organizer, verified=EXCLUDED.verified, dob=EXCLUDED.dob;')
w('')

w('-- Interests + home city: these are the inputs /api/discover ranks on. No prefs = cold feed.')
w('INSERT INTO user_prefs (user_id, categories, city, country, locale) VALUES')
w(people.map((p) => `  (${uref(p.email)}, ${arr(p.interests)}, ${q(p.city)}, 'Україна', 'uk')`).join(',\n'))
w('ON CONFLICT (user_id) DO UPDATE SET categories=EXCLUDED.categories, city=EXCLUDED.city, country=EXCLUDED.country;')
w('')

// ---------------------------------------------------------------- events
w('-- Events. starts_at is anchored to Kyiv wall-clock, so an "evening" event reads as evening.')
w('CREATE TEMP TABLE _ev (idx int PRIMARY KEY, id uuid NOT NULL);')
const sold = []
events.forEach((e, i) => {
  const org = people[eventOrg[i]]
  const poster = `https://picsum.photos/seed/${e.poster_seed}/900/1200`
  const price = e.cost_type === 'free' ? 0 : e.price_uah
  const age = e.age_rating && String(e.age_rating).length ? q(e.age_rating) : 'NULL'
  const start = `((date_trunc('day', (now() AT TIME ZONE 'Europe/Kyiv')) + interval '${e.days_from_now} days' + interval '${e.start_hour} hours') AT TIME ZONE 'Europe/Kyiv')`
  const end = `(${start} + interval '${Math.round(e.duration_hours * 60)} minutes')`
  // Past events look full; imminent ones are selling; distant ones have barely moved.
  const share = e.days_from_now < 0 ? 0.6 + rnd('s' + i) * 0.38
    : e.days_from_now < 21 ? 0.3 + rnd('s' + i) * 0.55
      : rnd('s' + i) * 0.35
  // Ticket ROWS and tickets_left must agree, or the organizer cabinet contradicts itself.
  // Distinct owners cap the row count, so capacity is capped to keep the two consistent.
  const cap = Math.min(e.tickets_total, attendees.length)
  const n = Math.max(0, Math.min(cap, Math.round(cap * share)))
  sold.push(n)
  w('WITH ins AS (')
  w('  INSERT INTO events (organizer_id, title, description, poster_url, category, city, venue_address,')
  w('    country, lat, lng, starts_at, ends_at, age_rating, price, currency, tickets_total, tickets_left,')
  w('    cost_type, status, timezone, created_at)')
  w(`  SELECT ${uref(org.email)}, ${q(e.title)}, ${q(e.description)}, ${q(poster)}, ${q(e.category)},`)
  w(`    ${q(e.city)}, ${q(e.venue)}, c.country, c.lat, c.lng, ${start}, ${end}, ${age}, ${price}, 'UAH',`)
  w(`    ${e.tickets_total}, ${Math.max(0, e.tickets_total - n)}, ${q(e.cost_type)}, 'published', 'Europe/Kyiv',`)
  w(`    now() - interval '${20 + (i % 40)} days'`)
  w(`  FROM cities c WHERE lower(c.name)=lower(${q(e.city)})`)
  w('  RETURNING id)')
  w(`INSERT INTO _ev (idx, id) SELECT ${i}, id FROM ins;`)
})
w('')

// ---------------------------------------------------------------- tickets + orders
w('-- Tickets and their orders. Escrow state is where the background sweep would have left it.')
let tn = 0
events.forEach((e, i) => {
  const past = e.days_from_now < 0
  const escrow = past ? (e.days_from_now < -14 ? 'cleared' : 'clearing') : 'held'
  for (let k = 0; k < sold[i]; k++) {
    const a = attendees[(i * 7 + k * 3) % attendees.length]
    const token = `seedqr-${i}-${k}`
    const price = e.cost_type === 'free' ? 0 : e.price_uah
    const validated = past && (i + k) % 4 !== 0
    const ago = Math.max(1, Math.abs(e.days_from_now) + 5)
    const esc = past && (i + k) % 5 === 0 && escrow === 'cleared' ? 'paid_out' : escrow
    w(`INSERT INTO tickets (event_id, owner_id, qr_token, status, price, validated_at, created_at)`)
    w(`  SELECT x.id, ${uref(a.email)}, ${q(token)}, 'active', ${price},`)
    w(`    ${validated ? `(SELECT starts_at + interval '25 minutes' FROM events WHERE id=x.id)` : 'NULL'},`)
    w(`    now() - interval '${ago} days' FROM _ev x WHERE x.idx=${i}`)
    w(`  ON CONFLICT DO NOTHING;`)
    if (e.cost_type !== 'free') {
      w(`INSERT INTO orders (event_id, buyer_id, amount, currency, status, escrow_status, provider, ticket_id, created_at)`)
      w(`  SELECT x.id, ${uref(a.email)}, ${price}, 'UAH', 'paid', ${q(esc)}, 'test', t.id,`)
      w(`    now() - interval '${ago} days' FROM _ev x JOIN tickets t ON t.qr_token=${q(token)} WHERE x.idx=${i};`)
    }
    tn++
  }
})
w('')

// ---------------------------------------------------------------- follows / saves
w('-- Follow graph. The shipped dev data had ZERO follows, so every social surface was empty.')
const follows = new Set()
people.forEach((p, i) => {
  const nOrg = 2 + Math.floor(rnd('fo' + i) * 4)
  for (let k = 0; k < nOrg; k++) {
    const o = organizers[(i * 5 + k * 2) % organizers.length]
    if (o.i !== i) follows.add(`${i}:${o.i}`)
  }
  const nPpl = 1 + Math.floor(rnd('fp' + i) * 4)
  for (let k = 0; k < nPpl; k++) {
    const a = attendees[(i * 3 + k * 7) % attendees.length]
    if (a.i !== i) follows.add(`${i}:${a.i}`)
  }
})
w('INSERT INTO follows (follower_id, followee_id, created_at) VALUES')
w([...follows].map((f) => {
  const [a, b] = f.split(':').map(Number)
  return `  (${uref(people[a].email)}, ${uref(people[b].email)}, now() - interval '${10 + (a % 40)} days')`
}).join(',\n'))
w('ON CONFLICT DO NOTHING;')
w('')

w('-- Saves ("цікавить") — the cheapest interest signal, and a direct input to discover ranking.')
const saves = new Set()
events.forEach((e, i) => {
  const n = 2 + Math.floor(rnd('sv' + i) * 9)
  for (let k = 0; k < n; k++) saves.add(`${(i * 11 + k * 5) % people.length}:${i}`)
})
w('INSERT INTO event_saves (user_id, event_id, created_at) VALUES')
w([...saves].map((s) => {
  const [pi, ei] = s.split(':').map(Number)
  return `  (${uref(people[pi].email)}, (SELECT id FROM _ev WHERE idx=${ei}), now() - interval '${1 + (ei % 25)} days')`
}).join(',\n'))
w('ON CONFLICT DO NOTHING;')
w('')

// ---------------------------------------------------------------- reviews
const rseen = new Set()
const rs = reviews.filter((r) => {
  const e = events[r.event_index]
  const p = people[r.person_index]
  if (!e || !p || e.days_from_now >= 0 || p.is_organizer) return false
  const key = `${r.event_index}:${r.person_index}`
  if (rseen.has(key)) return false
  rseen.add(key)
  return true
})
if (rs.length) {
  w('-- Reviews, only on events that have already happened.')
  w('INSERT INTO reviews (event_id, author_id, rating, text, created_at) VALUES')
  w(rs.map((r) => {
    const e = events[r.event_index]
    const days = Math.max(0, Math.abs(e.days_from_now) - Math.abs(r.days_ago_after_event || 0))
    return `  ((SELECT id FROM _ev WHERE idx=${r.event_index}), ${uref(people[r.person_index].email)},` +
      ` ${r.rating}, ${q(r.text)}, now() - interval '${days} days')`
  }).join(',\n') + ';')
  w('')
}

// ---------------------------------------------------------------- posts / comments / likes
if (posts.length) {
  w('-- Feed: posts, comments, likes.')
  w('CREATE TEMP TABLE _po (idx int PRIMARY KEY, id uuid NOT NULL);')
  posts.forEach((p, i) => {
    const author = people[p.author_index] ?? people[i % people.length]
    const isShare = p.kind === 'event_share' && Number.isInteger(p.event_index) && events[p.event_index]
    const kind = isShare ? 'event_share' : 'text'
    const ev = isShare ? `(SELECT id FROM _ev WHERE idx=${p.event_index})` : 'NULL'
    w('WITH ins AS (')
    w('  INSERT INTO posts (author_id, kind, text, event_id, created_at)')
    w(`  SELECT ${uref(author.email)}, ${q(kind)}, ${q(p.text)}, ${ev}, now() - interval '${Math.abs(p.days_ago || 0)} days'`)
    w('  RETURNING id)')
    w(`INSERT INTO _po (idx, id) SELECT ${i}, id FROM ins;`)
  })
  const cs = comments.filter((c) => posts[c.post_index] && people[c.author_index])
  if (cs.length) {
    w('INSERT INTO post_comments (post_id, author_id, text, created_at) VALUES')
    w(cs.map((c) => {
      const days = Math.max(0, Math.abs(posts[c.post_index].days_ago || 0) - Math.floor(Math.abs(c.hours_after_post || 0) / 24))
      return `  ((SELECT id FROM _po WHERE idx=${c.post_index}), ${uref(people[c.author_index].email)},` +
        ` ${q(c.text)}, now() - interval '${days} days')`
    }).join(',\n') + ';')
  }
  const likes = new Set()
  posts.forEach((p, i) => {
    const n = Math.floor(rnd('lk' + i) * 15)
    for (let k = 0; k < n; k++) likes.add(`${i}:${(i * 13 + k * 3) % people.length}`)
  })
  if (likes.size) {
    w('INSERT INTO post_likes (post_id, user_id, created_at) VALUES')
    w([...likes].map((l) => {
      const [pi, ui] = l.split(':').map(Number)
      return `  ((SELECT id FROM _po WHERE idx=${pi}), ${uref(people[ui].email)}, now() - interval '${1 + (pi % 20)} days')`
    }).join(',\n'))
    w('ON CONFLICT DO NOTHING;')
  }
  w('')
}

// ------------------------------------------------- the three standing test accounts
w('-- Keep the standing test accounts useful, so the owner can log straight in.')
w("UPDATE users SET role='ADMIN' WHERE lower(email)='admin@underground.dev';")
w("UPDATE users SET is_organizer=true, verified=true, dob='1990-05-14'")
w("  WHERE lower(email) IN ('maker@underground.dev','admin@underground.dev');")
w("UPDATE users SET dob='1994-08-02' WHERE lower(email)='user@underground.dev';")
w('-- Three upcoming events move to the maker account so the organizer cabinet is not empty.')
w("UPDATE events SET organizer_id=(SELECT id FROM users WHERE lower(email)='maker@underground.dev')")
w('  WHERE id IN (SELECT id FROM events WHERE starts_at > now() ORDER BY starts_at LIMIT 3);')
w('-- One ticket per event for the standing user, so "Мої квитки" and the QR screen have content.')
w("UPDATE tickets SET owner_id=(SELECT id FROM users WHERE lower(email)='user@underground.dev')")
w('  WHERE id IN (SELECT DISTINCT ON (t.event_id) t.id FROM tickets t JOIN events e ON e.id=t.event_id')
w('    WHERE e.starts_at > now() ORDER BY t.event_id, e.starts_at LIMIT 4);')
w("UPDATE orders o SET buyer_id=(SELECT id FROM users WHERE lower(email)='user@underground.dev')")
w('  FROM tickets t WHERE t.id=o.ticket_id')
w("    AND t.owner_id=(SELECT id FROM users WHERE lower(email)='user@underground.dev');")
w('INSERT INTO user_prefs (user_id, categories, city, country, locale)')
w("  SELECT id, ARRAY['electronic','dj set','stand-up','exhibition','food & drink']::text[], 'Київ', 'Україна', 'uk'")
w("  FROM users WHERE lower(email) IN ('user@underground.dev','maker@underground.dev','admin@underground.dev')")
w('ON CONFLICT (user_id) DO UPDATE SET categories=EXCLUDED.categories, city=EXCLUDED.city, country=EXCLUDED.country;')
w('INSERT INTO follows (follower_id, followee_id, created_at)')
w("  SELECT u.id, o.id, now() - interval '5 days' FROM users u, users o")
w("  WHERE lower(u.email)='user@underground.dev' AND o.is_organizer AND o.id <> u.id")
w('ON CONFLICT DO NOTHING;')
w('')

w('COMMIT;')
w('')
w("SELECT 'users' AS t, count(*) FROM users UNION ALL SELECT 'events', count(*) FROM events")
w("UNION ALL SELECT 'tickets', count(*) FROM tickets UNION ALL SELECT 'orders', count(*) FROM orders")
w("UNION ALL SELECT 'reviews', count(*) FROM reviews UNION ALL SELECT 'posts', count(*) FROM posts")
w("UNION ALL SELECT 'comments', count(*) FROM post_comments UNION ALL SELECT 'likes', count(*) FROM post_likes")
w("UNION ALL SELECT 'follows', count(*) FROM follows UNION ALL SELECT 'saves', count(*) FROM event_saves")
w("UNION ALL SELECT 'events geocoded', count(*) FROM events WHERE lat IS NOT NULL")
w("UNION ALL SELECT 'events upcoming', count(*) FROM events WHERE starts_at > now();")

process.stderr.write(`people=${people.length} events=${events.length} tickets=${tn} reviews=${rs.length} posts=${posts.length}\n`)
process.stdout.write(out.join('\n') + '\n')
